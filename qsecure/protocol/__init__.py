"""Teleportation-based measurement quantum digital signatures.

Alice teleports two copies of each key eigenstate to Bob and Charlie, who measure
on receipt in random bases and keep classical logs; they then swap records on
private coin flips and exchange matched counts. Verification scores only matched
positions against thresholds ``s_a < s_v < 1/2``.

Examples
--------
>>> import numpy as np
>>> from qsecure.protocol import ProtocolParams, QDSSession
>>> transcript = QDSSession(
...     ProtocolParams(key_length=24), rng=np.random.default_rng(0)
... ).run(1)
>>> transcript.transferable
True
"""

